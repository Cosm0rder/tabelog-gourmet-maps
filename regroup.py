def classify(genre_raw):
    tokens = [t.strip() for t in genre_raw.split('、')]
    # 第1ジャンル優先
    first = tokens[0] if tokens else ''
    for cat, kws in RULES:
        for kw in kws:
            if kw in first:
                return cat, 'first'
    # 全文スキャン
    for cat, kws in RULES:
        for kw in kws:
            if kw in genre_raw:
                return cat, 'full'
    return 'その他', 'none'

